#!/usr/bin/env python3
"""Builds supabase/functions/api/index.js: one file with the old Google code (Code.gs + Staff.gs)
running on the Nikadi database, plus the server. Run after tools/build-staff.py."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
api = root / 'supabase/functions/api'
def mod(name):
    s = (api / name).read_text()
    s = re.sub(r'^export (function|var|const|let) ', r'\1 ', s, flags=re.M)
    return s
code = (root / 'backend/Code.gs').read_text()
staff = (root / 'backend/Staff.gs').read_text()
OVERRIDE = ['deskDb_', 'deskSavePhoto_', 'deskGetPhoto_', 'deskStayFolder_', 'deskTrash_', 'deskOwnBillFile_', 'deskSendBill_', 'deskArchive_', 'waSaveMedia_']
gas = code + '\n' + staff
for f in OVERRIDE:
    n = len(re.findall(r'\bfunction ' + f + r'\(', gas))
    assert n == 1, (f, n)
    gas = re.sub(r'\bfunction ' + f + r'\(', 'function ' + f + 'GAS_(', gas)
overrides = '''
/* ===== on the Nikadi server: data from the database, Google work through the bridge ===== */
function deskDb_() { return CTX.db; }
function deskSavePhoto_(b64, name, month, rootName, folderId) { return nkBridge_('deskSavePhoto_', [b64, name, month, rootName, folderId]); }
function deskGetPhoto_(fileId) { return nkBridge_('deskGetPhoto_', [fileId]); }
function deskStayFolder_(rec, oldId) { return nkBridge_('deskStayFolder_', [rec, oldId]); }
function deskTrash_(id) { if (id) nkBridge_('deskTrash_', [id]); }
function deskOwnBillFile_(b64, name, ym) { return nkBridge_('deskOwnBillFile_', [b64, name, ym]); }
function deskSendBill_(d, to, pdf) { return nkBridge_('deskSendBill_', [d, to, pdf]); }
function deskArchive_(rec, was) { return nkBridge_('deskArchive_', [rec, was]); }
function waSaveMedia_(media, type, phone, name) { return nkBridge_('waSaveMedia_', [media, type, phone, name]); }
'''
out = ['/* GENERATED by tools/build-edge.py from backend/Code.gs + backend/Staff.gs + supabase/functions/api/*.js. Do not edit here. */',
       mod('nkcrypto.js'), mod('nkdb.js'), mod('prelude.js'),
       '/* ===================== backend/Code.gs + backend/Staff.gs ===================== */', gas,
       overrides, mod('server.js'), mod('special.js'),
       "if (typeof Deno !== 'undefined' && Deno.serve) Deno.serve(nkServe);",
       'export { nkHandle, nkServe };', 'export function nkBase() { return NK_BASE; }', 'export function nkReset() { NK_BASE = { versions: {}, tables: {}, kv: {} }; }']
(api / 'index.js').write_text('\n'.join(out))
print('supabase/functions/api/index.js written', len('\n'.join(out)) // 1024, 'KB')
